"""Generates proxy/winmm_exports.h and proxy/winmm.def from the 32-bit system winmm.dll.

The proxy winmm.dll exports everything the real one does (same names and ordinals),
so any module in the game process that imports winmm keeps working.

Usage (needs the 'pefile' package):
    python tools/gen_winmm_proxy.py [path\\to\\SysWOW64\\winmm.dll]
"""
import os
import sys

import pefile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DLL = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "SysWOW64", "winmm.dll")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_DLL
    pe = pefile.PE(path, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    exports = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda s: s.ordinal)

    header = [
        "// Generated by tools/gen_winmm_proxy.py from %s. Do not edit." % os.path.basename(path),
        "// WINMM_EXPORT(index, stub name, export name or NULL, ordinal)",
    ]
    deffile = ["LIBRARY winmm", "EXPORTS"]
    for index, sym in enumerate(exports):
        if sym.name:
            name = sym.name.decode()
            stub = "Stub_" + name
            header.append('WINMM_EXPORT(%d, %s, "%s", %d)' % (index, stub, name, sym.ordinal))
            deffile.append("    %s=%s @%d" % (name, stub, sym.ordinal))
        else:
            stub = "Stub_Ordinal%d" % sym.ordinal
            header.append("WINMM_EXPORT(%d, %s, NULL, %d)" % (index, stub, sym.ordinal))
            deffile.append("    %s @%d NONAME" % (stub, sym.ordinal))
    header.append("#define WINMM_EXPORT_COUNT %d" % len(exports))

    with open(os.path.join(ROOT, "proxy", "winmm_exports.h"), "w", newline="\n") as f:
        f.write("\n".join(header) + "\n")
    with open(os.path.join(ROOT, "proxy", "winmm.def"), "w", newline="\n") as f:
        f.write("\n".join(deffile) + "\n")
    print("Wrote %d exports" % len(exports))


if __name__ == "__main__":
    main()
