"""Generates src/tfe_classes.inc from the First Encounter entity sources (.es).

A TFE world stores each entity property as (property ID << 8 | type) followed by
the value, but not the property's name.  The converter needs the names to find
the matching property in the alpha's classes, so this script extracts, for each
TFE class: its class ID, C++ name, base class and properties (index, type,
identifier and editor name), plus the enums with their values and editor names.

Usage: python gen_tfe_classes.py [-o output.inc] <folder with .es files>...

Give it TFE's Sources/Entities and the engine's Sources/Engine/Classes (the
engine's own MovableEntity, MovableModelEntity... whose properties every
moving entity also saves).  The sources are in Croteam's GPL release of
Serious Engine 1 (https://github.com/Croteam-official/Serious-Engine for the
engine; SamTFE/Sources/Entities for example in
https://github.com/tx00100xt/SeriousSamClassic).
"""
import os
import re
import sys

RE_BLOCK_COMMENT = re.compile(r'/\*.*?\*/', re.S)
RE_CLASS = re.compile(r'^\s*class\s+(?:export\s+)?(\w+)\s*:\s*(\w+)\s*\{', re.M)
RE_NAME = re.compile(r'^\s*name\s+"([^"]*)"\s*;', re.M)
RE_ENUM = re.compile(r'^\s*enum\s+(\w+)\s*\{(.*?)\}\s*;', re.M | re.S)
RE_ENUM_VALUE = re.compile(r'(-?\d+)\s+(\w+)\s+"([^"]*)"')
RE_PROPERTY = re.compile(r'^\s*(\d+)\s+((?:enum|flags)\s+\w+|\w+)\s+(\w+)\s*(?:"([^"]*)")?')


def strip_comments(text):
    text = RE_BLOCK_COMMENT.sub('', text)
    out = []
    for line in text.split('\n'):
        # cut // comments outside of strings
        in_str = False
        for i, ch in enumerate(line):
            if ch == '"' and (i == 0 or line[i - 1] != '\\'):
                in_str = not in_str
            elif not in_str and line.startswith('//', i):
                line = line[:i]
                break
        out.append(line)
    return '\n'.join(out)


def class_id(text):
    # the class ID is the first line holding only a number, before the first %{
    for line in text.split('\n'):
        s = line.strip()
        if s.startswith('%{'):
            break
        if s.isdigit():
            return int(s)
    return None


def parse_es(path, enums, classes):
    text = strip_comments(open(path, encoding='latin-1').read())
    for m in RE_ENUM.finditer(text):
        vals = [(int(v), ident, disp) for v, ident, disp in RE_ENUM_VALUE.findall(m.group(2))]
        enums.setdefault(m.group(1), vals)
    mc = RE_CLASS.search(text)
    if not mc:
        return
    cid = class_id(text)
    mn = RE_NAME.search(text, mc.end())
    props = []
    pstart = text.find('properties:', mc.end())
    if pstart >= 0:
        pend = text.find('components:', pstart)
        if pend < 0:
            pend = text.find('functions:', pstart)
        section = text[pstart + len('properties:'):pend if pend >= 0 else len(text)]
        # the { ... } block at the end holds members that aren't saved
        brace = section.find('\n{')
        if brace >= 0:
            section = section[:brace]
        for line in section.split('\n'):
            mp = RE_PROPERTY.match(line)
            if mp:
                ptype = ' '.join(mp.group(2).split())
                props.append((int(mp.group(1)), ptype, mp.group(3), mp.group(4) or ''))
    classes.append((cid, mc.group(1), mc.group(2), mn.group(1) if mn else mc.group(1)[1:], props))


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    args = sys.argv[1:]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'tfe_classes.inc')
    if len(args) >= 2 and args[0] == '-o':
        out = args[1]
        args = args[2:]
    if not args:
        print(__doc__)
        sys.exit(1)
    enums = {}
    classes = []
    for src in args:
        for fn in sorted(os.listdir(src)):
            if fn.lower().endswith('.es'):
                parse_es(os.path.join(src, fn), enums, classes)
    lines = []
    for cid, cpp, base, name, props in classes:
        lines.append('C %d %s %s %s' % (cid if cid is not None else -1, cpp, base, name))
        for idx, ptype, ident, disp in props:
            lines.append('P %d %s|%s|%s' % (idx, ptype, ident, disp))
    for ename in sorted(enums):
        lines.append('E %s' % ename)
        for v, ident, disp in enums[ename]:
            lines.append('V %d %s|%s' % (v, ident, disp))
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by tools/gen_tfe_classes.py from the First Encounter entity sources.\n')
        f.write('// C <class ID> <C++ name> <base> <name>; P <index> <type>|<identifier>|<editor name>;\n')
        f.write('// E <enum>; V <value> <identifier>|<editor name>\n')
        for l in lines:
            f.write('  %s,\n' % c_string(l))
    print('%d classes, %d enums -> %s' % (len(classes), len(enums), out))


if __name__ == '__main__':
    main()
